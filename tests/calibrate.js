#!/usr/bin/env node
// Regenerates EXP_TABLE (the expedition outcome model) in src/js/balance.js from bot runs of tests/sim.js at several upgrade levels.
// Usage: node tests/calibrate.js [--runs 60] [--seed 1] [--levels fresh=0,mid=800,heavy=3000,high=8000,maxed=999999]
// Per class and level it records: share of runs ending on each floor (index 8 = won), mean gold and kills of those runs, mean turns, and manual
// gold per hour (mean gold per run / (mean turns x BAL.exp.turnSec)). The row's pw is the mean upgrade power (gold put into levels) of the runs.
// Then run `node build.js`. Heat 0, bot play, no Auto.
'use strict';
const fs = require('fs'), path = require('path'), cp = require('child_process');
const arg = (n, d) => { const i = process.argv.indexOf('--' + n); return i > 0 ? process.argv[i + 1] : d; };
const RUNS = arg('runs', '60'), SEED = arg('seed', '1'), LEVELS = arg('levels', 'fresh=0,mid=800,heavy=3000,high=8000,maxed=999999');
const TURN_SEC = 1.2;
const out = path.join(require('os').tmpdir(), 'calib_' + process.pid + '.jsonl');
cp.execFileSync('node', [path.join(__dirname, 'sim.js'), '--runs', RUNS, '--levels', LEVELS, '--seed', SEED, '--jsonl', out], { stdio: ['ignore', 'ignore', 'inherit'] });
const rows = fs.readFileSync(out, 'utf8').trim().split('\n').map((l) => JSON.parse(l));
const names = LEVELS.split(',').map((s) => s.split('=')[0]);
const r1 = (x) => Math.round(x * 100) / 100;
const table = {};
for (const cls of ['warrior', 'mage', 'rogue']) {
  table[cls] = [];
  for (const lv of names) {
    const x = rows.filter((r) => r.cls === cls && r.level === lv && !r.stall);
    if (!x.length) continue;
    const reach = Array(9).fill(0), gold = Array(9).fill(0), kills = Array(9).fill(0);
    for (const r of x) { const i = r.won ? 8 : Math.min(7, r.floor - 1); reach[i]++; gold[i] += r.gold; kills[i] += r.kills; }
    const n = x.length, avgG = x.reduce((a, r) => a + r.gold, 0) / n, avgT = x.reduce((a, r) => a + r.turns, 0) / n;
    // floors nobody ended on borrow the mean of all runs (they carry no weight anyway)
    table[cls].push({ pw: Math.round(x.reduce((a, r) => a + r.pw, 0) / n), reach: reach.map((c) => r1(c / n)), gold: gold.map((g, i) => reach[i] ? Math.round(g / reach[i]) : Math.round(avgG)), kills: kills.map((k, i) => reach[i] ? Math.round(k / reach[i]) : 0), turns: Math.round(avgT), gph: Math.round(avgG / (avgT * TURN_SEC / 3600)) });
  }
}
// reach must sum to 1 exactly enough for the sampler: renormalise
for (const c in table) for (const row of table[c]) { const s = row.reach.reduce((a, b) => a + b, 0); row.reach = row.reach.map((v) => r1(v / s)); }
const f = path.join(__dirname, '..', 'src', 'js', 'balance.js');
let s = fs.readFileSync(f, 'utf8');
const a = s.indexOf('// BEGIN EXP_TABLE'), b = s.indexOf('// END EXP_TABLE');
if (a < 0 || b < 0) throw new Error('markers missing');
s = s.slice(0, a) + '// BEGIN EXP_TABLE (generated by tests/calibrate.js: runs ' + RUNS + ' per cell, seed ' + SEED + ', levels ' + LEVELS + ')\nconst EXP_TABLE=' + JSON.stringify(table).replace(/"(warrior|mage|rogue|pw|reach|gold|kills|turns|gph)":/g, '$1:') + ';\n' + s.slice(b);
fs.writeFileSync(f, s);
for (const c in table) console.log(c.padEnd(8) + table[c].map((r) => 'pw ' + r.pw + ' gph ' + r.gph + ' turns ' + r.turns).join(' | '));
fs.unlinkSync(out);
